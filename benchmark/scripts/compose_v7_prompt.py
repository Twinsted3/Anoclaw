"""Read refine-logs/tool_cards/*.md and emit agent_tool_hints_v7.py with
structured TOOL_HINTS string for injection into agent_prompt_v7.

Only ACTIONABLE positive niches are injected (not diagnostic-only
domain labels). If a tool has only anti-niches, it's listed as AVOID.
"""
from __future__ import annotations
import re
import sys
from pathlib import Path

CARDS = Path(__file__).resolve().parent.parent.parent / "refine-logs" / "tool_cards"
OUT = Path(__file__).resolve().parent / "agent_tool_hints_v7.py"


def extract_agent_hint(card_text: str) -> tuple[str, bool]:
    """Return (hint_text, is_keep) extracted from the card.

    Looks for the final "## Agent hint" section, falling back to generic
    templates if nothing extractable.
    """
    is_keep = "**Verdict:** KEEP" in card_text
    m = re.search(r"## Agent hint.*?\n\n(.+?)(?=\n##|\Z)",
                  card_text, re.DOTALL)
    if m:
        return m.group(1).strip(), is_keep
    return ("(no hint extracted)", is_keep)


def main():
    if not CARDS.exists():
        print("[compose_v7] no tool_cards dir; writing placeholder hints",
              file=sys.stderr)
        OUT.write_text('TOOL_HINTS = "(no tool cards generated yet)"\n')
        return
    md_files = sorted(CARDS.glob("*.md"))
    if not md_files:
        print("[compose_v7] no tool card files; writing placeholder",
              file=sys.stderr)
        OUT.write_text('TOOL_HINTS = "(no tool cards generated yet)"\n')
        return

    keep_lines: list[str] = []
    drop_lines: list[str] = []
    for md in md_files:
        text = md.read_text()
        tool = md.stem
        hint, is_keep = extract_agent_hint(text)
        line = f"- {tool}: {hint}"
        if is_keep:
            keep_lines.append(line)
        else:
            drop_lines.append(line)

    parts = []
    if keep_lines:
        parts.append("VALIDATED TOOLS (use when their niche condition fires):")
        parts.extend(keep_lines)
    if drop_lines:
        parts.append("")
        parts.append("NON-VALIDATED TOOLS (no documented prompt-actionable "
                     "niche on dev; avoid unless you have a strong hypothesis):")
        parts.extend(drop_lines)

    content = ('"""Auto-generated by compose_v7_prompt.py from tool_cards/*.md. '
               'Do NOT edit by hand."""\n\n'
               f"TOOL_HINTS = {repr(chr(10).join(parts))}\n")
    OUT.write_text(content)
    print(f"[compose_v7] wrote {OUT}")
    print(f"[compose_v7] KEEP tools: {len(keep_lines)}")
    print(f"[compose_v7] DROP tools: {len(drop_lines)}")


if __name__ == "__main__":
    main()
